-- Deletes read the keys of the attachment files still kept (`expired = false`)
-- before their cascade takes the rows (utils/attachmentBlobs.ts). Expired rows
-- are kept forever for the "File expired" placeholder, so they are most of the
-- table, and no index held `expired`: every such read filtered the table's
-- whole history. With `expired` leading, the live rows are one contiguous range
-- in id order. Written as Prisma generates it for `@@index([expired, id])`
-- (`prisma migrate diff --from-schema … --to-schema … --script`).
--
-- Locks: a plain CREATE INDEX holds a SHARE lock on "message_attachments" for
-- the whole build, one full pass over the table: while it runs, every write
-- to it blocks (new attachments, the nightly expiry, and the cascade of every
-- message, channel, conversation, space or account delete), reads do not.
-- Harmless under maintenance mode; an online or rolling deploy takes the
-- route below.
--
-- NOTE: for an online or rolling deploy, or a very large `message_attachments`
-- table: build the index with `CREATE INDEX CONCURRENTLY
-- "message_attachments_expired_id_idx" ON "message_attachments"("expired",
-- "id")` OUTSIDE any transaction (CONCURRENTLY cannot run inside one), then
-- mark this migration applied with
-- `prisma migrate resolve --applied 20261111120000_message_attachments_live_index`.
CREATE INDEX "message_attachments_expired_id_idx" ON "message_attachments"("expired", "id");
