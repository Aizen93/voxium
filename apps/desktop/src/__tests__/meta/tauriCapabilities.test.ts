// @vitest-environment node
// Pure filesystem check: what the webview may ask the Rust side for. The
// capability file is the whole grant; external links are opened by the
// opener plugin's open_url, scoped to the schemes the app links to, and the
// deprecated shell plugin (which also carries process-execution commands the
// app never used) is gone from every place it was declared.
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DESKTOP = fileURLToPath(new URL('../../../', import.meta.url));
const read = (p: string) => readFileSync(DESKTOP + p, 'utf8').replace(/\r\n/g, '\n');

type Permission = string | { identifier: string; allow?: unknown; deny?: unknown };
const capability = JSON.parse(read('src-tauri/capabilities/default.json')) as {
  identifier: string;
  windows: string[];
  permissions: Permission[];
};
const identifierOf = (p: Permission) => (typeof p === 'string' ? p : p.identifier);

/** The opener grant, exactly: open a URL with its default application, for these schemes only. */
const OPENER = {
  identifier: 'opener:allow-open-url',
  allow: [{ url: 'http://*' }, { url: 'https://*' }, { url: 'mailto:*' }],
};

describe('the capability file', () => {
  it('grants exactly these permissions', () => {
    expect(capability.identifier).toBe('default');
    expect(capability.windows).toEqual(['main', 'splash']);
    expect(capability.permissions).toEqual([
      'core:default',
      'core:window:allow-start-dragging',
      'core:window:allow-minimize',
      'core:window:allow-toggle-maximize',
      'core:window:allow-is-maximized',
      'core:window:allow-close',
      'core:window:allow-set-icon',
      'core:window:allow-show',
      'core:window:allow-hide',
      'core:window:allow-set-focus',
      'core:window:allow-unminimize',
      'core:window:allow-destroy',
      'core:webview:allow-webview-close',
      OPENER,
      'notification:default',
      'notification:allow-is-permission-granted',
      'notification:allow-request-permission',
      'notification:allow-notify',
      'notification:allow-show',
      'updater:default',
      'process:allow-restart',
    ]);
  });

  it('holds nothing of the shell plugin', () => {
    expect(capability.permissions.filter((p) => identifierOf(p).startsWith('shell:'))).toEqual([]);
  });

  it('opens URLs for http, https and mailto only, with the default application, and nothing else of the opener', () => {
    const opener = capability.permissions.filter((p) => identifierOf(p).startsWith('opener:'));
    expect(opener).toEqual([OPENER]);
    // no `app` key: only the system's default application, never a named program
    for (const entry of OPENER.allow) expect(Object.keys(entry)).toEqual(['url']);
  });

  it('is what the build compiled (gen/schemas, regenerated by tauri-build and committed)', () => {
    const compiled = JSON.parse(read('src-tauri/gen/schemas/capabilities.json')) as Record<string, { permissions: Permission[] }>;
    expect(compiled.default.permissions).toEqual(capability.permissions);
  });
});

describe('the opener plugin replaces the shell plugin', () => {
  const cargo = read('src-tauri/Cargo.toml');
  const lib = read('src-tauri/src/lib.rs');
  const code = lib.slice(0, lib.indexOf('\n#[cfg(test)]'));
  const pkg = JSON.parse(read('package.json')) as { dependencies: Record<string, string>; devDependencies: Record<string, string> };

  it('is the dependency, on both sides', () => {
    expect(cargo).toMatch(/^tauri-plugin-opener = "2"$/m);
    expect(cargo).not.toContain('tauri-plugin-shell');
    expect(pkg.dependencies['@tauri-apps/plugin-opener']).toMatch(/^\^2\./);
    expect({ ...pkg.dependencies, ...pkg.devDependencies }).not.toHaveProperty('@tauri-apps/plugin-shell');
  });

  it("is registered without its own injected click script: the app's handler is the one place links open from", () => {
    expect(code).not.toContain('tauri_plugin_shell');
    expect(code).toMatch(/\.plugin\(\s*tauri_plugin_opener::Builder::new\(\)\s*\.open_js_links_on_click\(false\)\s*\.build\(\),?\s*\)/);
    expect(code).not.toContain('tauri_plugin_opener::init()');
    expect(code.match(/tauri_plugin_opener::/g)).toHaveLength(1);
  });
});
